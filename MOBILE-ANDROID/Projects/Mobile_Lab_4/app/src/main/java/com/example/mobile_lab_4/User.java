package com.example.mobile_lab_4;

public class User {
    public int id;
    public String name;
    public String phone;
    public String image;

    public User() {
    }

    public User(int id, String name, String phone, String image) {
        this.id = id;
        this.name = name;
        this.phone = phone;
        this.image = image;
    }
}
